"""M7: exact finite-horizon scheduling and causal dispatch on the V1 engine.

CP-SAT selects dispatches and robot states at each integer tick. Local transition
tables are generated by Simulation.step itself, not by a second physical model.
Station grants encode ID priority; holders releasing this tick still occupy it.
All tasks are mandatory. Objectives are total tardiness, then makespan.
"""

import argparse
from copy import deepcopy
from dataclasses import dataclass
from itertools import permutations, product
import json
import math
from pathlib import Path
from time import perf_counter

from .allocation import fifo
from .engine import Simulation
from .instances import from_dict, load_instance
from .metrics import metrics
from .models import Grid, Instance, Resource, Robot, RobotState, Task, TaskState
from .paths import shortest_path


@dataclass(frozen=True)
class TemporalObservation:
    """Detached revealed state. No configuration, future tasks, or outage calendar."""

    tick: int
    grid: Grid
    robots: tuple[Robot, ...]
    tasks: tuple[Task, ...]
    resources: tuple[Resource, ...]


def temporal_observation(simulation: Simulation) -> TemporalObservation:
    return TemporalObservation(
        simulation.tick, simulation.grid,
        tuple(deepcopy(r) for r in sorted(simulation.robots.values(), key=lambda r: r.id)),
        tuple(deepcopy(t) for t in sorted(simulation.tasks.values(), key=lambda t: t.id)
              if t.arrival_tick <= simulation.tick and t.state != TaskState.COMPLETED),
        tuple(deepcopy(r) for r in sorted(simulation.resources.values(), key=lambda r: r.id)))


def _key(robot: Robot) -> tuple:
    return (robot.position, robot.state, robot.task_id, tuple(robot.path),
            robot.handling_remaining, robot.resource_id)


def _local_tables(view: TemporalObservation, robot: Robot, codes: dict, resources: dict):
    """Enumerate finite local states through actual engine transitions.

    A capacity of zero is used only inside this transition oracle to ask the
    existing engine for its blocked-acquisition transition. It is never exported
    or used in a real simulation. Global capacity is imposed in the CP model.
    """
    allowed = [t for t in view.tasks if t.load <= robot.capacity
               and shortest_path(view.grid, robot.position, t.pickup) is not None]
    initial = Instance(view.grid, {robot.id: Robot(robot.id, robot.position, robot.capacity)},
                       {t.id: deepcopy(t) for t in allowed},
                       {r.id: Resource(r.id, r.position, r.capacity) for r in view.resources}, 2)
    for task in initial.tasks.values():
        task.arrival_tick = 0
    states, indexes = [deepcopy(robot)], {_key(robot): 0}
    tables = {False: [], True: []}
    index = 0
    while index < len(states):
        source = states[index]
        choices = [None] + ([t.id for t in allowed] if source.state == RobotState.IDLE else [])
        for task_id, suspended, blocked in product(choices, (False, True), (False, True)):
            simulation = Simulation(initial)
            local = deepcopy(source)
            local.unavailable = False
            simulation.robots[robot.id] = local
            if local.task_id:
                task = simulation.tasks[local.task_id]
                task.robot_id = robot.id
                task.state = (TaskState.ASSIGNED if local.state in {
                    RobotState.TO_PICKUP, RobotState.PICKING, RobotState.WAITING_PICKUP}
                    else TaskState.PICKED_UP)
                if local.resource_id:
                    simulation.resources[local.resource_id].holders.add(robot.id)
            if task_id is not None:
                simulation.assign(robot.id, task_id)
            requested = simulation._resources_at.get(local.position)
            request = (requested.id if not suspended and local.task_id and not local.path
                       and local.resource_id is None and requested else None)
            if blocked and request is None:
                continue
            if blocked:
                requested.capacity = 0
            if suspended:
                simulation._unavailability = [dict(robot_id=robot.id, start_tick=1, end_tick=2)]
            simulation.step()
            target = simulation.robots[robot.id]
            key = _key(target)
            if key not in indexes:
                indexes[key] = len(states)
                states.append(deepcopy(target))
            def event_code(kind, mapping, field):
                return next((mapping[e[field]] for e in simulation.events if e['kind'] == kind), 0)
            tables[suspended].append((
                index, codes.get(task_id, 0), int(blocked), indexes[key], resources.get(request, 0),
                event_code('resource_acquired', resources, 'resource_id'),
                event_code('collected', codes, 'task_id'),
                event_code('delivered', codes, 'task_id')))
        index += 1
    return states, tables


def _budget(value):
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or value <= 0:
        raise ValueError('budget must be a finite positive number')


def plan_schedule(view: TemporalObservation, horizon: int, *, budget: float = 1.0,
                  calendar: tuple[dict, ...] = ()) -> dict:
    """Plan all observed unfinished tasks through absolute horizon.

    calendar is explicit offline information. Rolling never supplies it. Without
    a calendar, current unavailable robots cannot dispatch now; future ticks use
    an explicit optimistic availability forecast, corrected by replanning.
    """
    from ortools.sat.python import cp_model

    _budget(budget)
    if type(horizon) is not int or horizon < view.tick:
        raise ValueError('horizon must be an integer at or after the observation tick')
    started = perf_counter()
    tasks = {t.id: t for t in view.tasks}
    codes = {task_id: i + 1 for i, task_id in enumerate(tasks)}
    resources = {r.id: i + 1 for i, r in enumerate(view.resources)}
    size = horizon - view.tick
    result = dict(status='UNKNOWN', feasible=False, optimal=False, phases=[], assignments=[], tasks={},
                  objective=None, start_tick=view.tick, horizon=horizon,
                  solver_seconds=0.0, total_seconds=0.0,
                  budget_per_phase=budget, budget_unit='deterministic_time')
    if not tasks:
        result.update(status='OPTIMAL', feasible=True, optimal=True, objective=[0, view.tick])
        result['total_seconds'] = perf_counter() - started
        return result
    model = cp_model.CpModel()
    dispatch, collect, deliver, holders, requests, acquisitions, blocked = {}, {}, {}, {}, {}, {}, {}
    def equals(variable, value, name):
        indicator = model.new_bool_var(name)
        model.add(variable == value).only_enforce_if(indicator)
        model.add(variable != value).only_enforce_if(indicator.Not())
        return indicator
    def unavailable(robot, tick):
        return any(e['robot_id'] == robot.id and e['start_tick'] <= tick < e['end_tick']
                   for e in calendar) or (tick == view.tick and robot.unavailable)
    for robot in view.robots:
        states, tables = _local_tables(view, robot, codes, resources)
        sequence = [model.new_int_var(0, len(states) - 1, f'{robot.id}_state_{t}')
                    for t in range(size + 1)]
        model.add(sequence[0] == 0)
        for offset in range(size):
            tick = view.tick + offset
            choice = model.new_int_var(0, len(tasks), f'{robot.id}_dispatch_{tick}')
            block = model.new_bool_var(f'{robot.id}_blocked_{tick}')
            request = model.new_int_var(0, len(resources), f'{robot.id}_request_{tick}')
            acquire = model.new_int_var(0, len(resources), f'{robot.id}_acquire_{tick}')
            pickup = model.new_int_var(0, len(tasks), f'{robot.id}_collect_{tick}')
            delivery = model.new_int_var(0, len(tasks), f'{robot.id}_deliver_{tick}')
            model.add_allowed_assignments(
                [sequence[offset], choice, block, sequence[offset + 1], request, acquire, pickup, delivery],
                tables[unavailable(robot, tick + 1)])
            blocked[robot.id, offset] = block
            if unavailable(robot, tick):
                model.add(choice == 0)
            for task_id, code in codes.items():
                dispatch[robot.id, task_id, offset] = equals(choice, code, f'd_{robot.id}_{code}_{tick}')
                collect[robot.id, task_id, offset] = equals(pickup, code, f'p_{robot.id}_{code}_{tick}')
                deliver[robot.id, task_id, offset] = equals(delivery, code, f'e_{robot.id}_{code}_{tick}')
                if tasks[task_id].arrival_tick > tick or tasks[task_id].state in {TaskState.ASSIGNED, TaskState.PICKED_UP}:
                    model.add(dispatch[robot.id, task_id, offset] == 0)
            for resource_id, code in resources.items():
                requests[robot.id, resource_id, offset] = equals(request, code, f'q_{robot.id}_{code}_{tick}')
                acquisitions[robot.id, resource_id, offset] = equals(acquire, code, f'a_{robot.id}_{code}_{tick}')
                held = model.new_bool_var(f'h_{robot.id}_{code}_{tick}')
                model.add_allowed_assignments([sequence[offset], held],
                    [(i, int(state.resource_id == resource_id)) for i, state in enumerate(states)])
                holders[robot.id, resource_id, offset] = held
    robots = sorted(r.id for r in view.robots)
    for resource in view.resources:
        for offset in range(size):
            occupied = sum(holders[r, resource.id, offset] for r in robots)
            for index, robot_id in enumerate(robots):
                used = occupied + sum(acquisitions[r, resource.id, offset] for r in robots[:index])
                request = requests[robot_id, resource.id, offset]
                block = blocked[robot_id, offset]
                model.add(used < resource.capacity).only_enforce_if([request, block.Not()])
                model.add(used >= resource.capacity).only_enforce_if([request, block])
    completions, tardiness = {}, []
    for task_id, task in tasks.items():
        assigned = [dispatch[r, task_id, t] for r in robots for t in range(size)]
        model.add(sum(assigned) == int(task.state in {TaskState.PENDING, TaskState.SCHEDULED}))
        endings = [(view.tick + t + 1, deliver[r, task_id, t]) for r in robots for t in range(size)]
        model.add(sum(value for _, value in endings) == 1)
        completion = model.new_int_var(view.tick, horizon, f'completion_{task_id}')
        model.add(completion == sum(t * value for t, value in endings))
        completions[task_id] = completion
        if task.deadline is not None:
            late = model.new_int_var(0, max(0, horizon - task.deadline), f'late_{task_id}')
            model.add_max_equality(late, [0, completion - task.deadline])
            tardiness.append(late)
    makespan = model.new_int_var(view.tick, horizon, 'makespan')
    model.add_max_equality(makespan, list(completions.values()))
    total_tardiness = sum(tardiness)
    model.minimize(total_tardiness)
    solver = cp_model.CpSolver()
    solver.parameters.num_search_workers = 1
    solver.parameters.random_seed = 0
    solver.parameters.max_deterministic_time = budget
    def solve():
        before = perf_counter()
        status = solver.solve(model)
        result['solver_seconds'] += perf_counter() - before
        result['phases'].append(solver.status_name(status))
        if status == cp_model.MODEL_INVALID:
            raise RuntimeError(model.validate())
        return status
    def extract():
        result['assignments'] = sorted([
            dict(tick=view.tick + t, robot_id=r, task_id=task_id)
            for (r, task_id, t), value in dispatch.items() if solver.value(value)],
            key=lambda a: (a['tick'], a['robot_id']))
        result['tasks'] = {task_id: dict(
            collected_tick=next((view.tick + t + 1 for r in robots for t in range(size)
                                 if solver.value(collect[r, task_id, t])), None),
            completed_tick=solver.value(completions[task_id])) for task_id in tasks}
        result['objective'] = [solver.value(total_tardiness), solver.value(makespan)]
    first = solve()
    if first in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        result['feasible'] = True
        extract()
        result['status'] = solver.status_name(first)
        if first == cp_model.OPTIMAL:
            model.add(total_tardiness == result['objective'][0])
            model.minimize(makespan)
            second = solve()
            result['status'] = solver.status_name(second)
            if second in (cp_model.OPTIMAL, cp_model.FEASIBLE):
                extract()
            result['optimal'] = second == cp_model.OPTIMAL
    else:
        result['status'] = solver.status_name(first)
    result['total_seconds'] = perf_counter() - started
    return result


def solve_schedule(instance: Instance, *, budget: float = 1.0) -> dict:
    """Offline oracle: all tasks and declared calendar are explicitly known."""
    simulation = Simulation(instance)
    view = temporal_observation(simulation)
    view = TemporalObservation(view.tick, view.grid, view.robots,
                               tuple(deepcopy(t) for t in simulation.tasks.values()), view.resources)
    return plan_schedule(view, instance.horizon, budget=budget, calendar=tuple(instance.unavailability))


def execute_schedule(instance: Instance, plan: dict) -> tuple[Simulation, dict]:
    """Replay dispatch dates; never force handling dates or mutate robot paths."""
    simulation = Simulation(instance)
    deviations, rejected = [], []
    by_tick = {}
    for action in plan['assignments']:
        by_tick.setdefault(action['tick'], []).append(action)
    while not simulation.finished:
        for action in by_tick.get(simulation.tick, []):
            try:
                simulation.assign(action['robot_id'], action['task_id'])
            except ValueError as error:
                rejected.append(dict(**action, reason=str(error)))
        simulation.step()
    for task_id, dates in plan['tasks'].items():
        collected = next((e['tick'] for e in simulation.events
                          if e['kind'] == 'collected' and e['task_id'] == task_id), None)
        completed = simulation.tasks[task_id].completed_tick
        deviations.append(dict(task_id=task_id,
            collected_delta=None if collected is None or dates['collected_tick'] is None else collected - dates['collected_tick'],
            completed_delta=None if completed is None else completed - dates['completed_tick']))
    valid = (not rejected and simulation.all_tasks_completed
             and all(d['collected_delta'] in (0, None) and d['completed_delta'] == 0 for d in deviations))
    return simulation, dict(executable=valid, rejected_dispatches=rejected, deviations=deviations)


def run_rolling(instance: Instance, *, window: int = 20, frequency: int = 3,
                budget: float = 1.0) -> tuple[Simulation, dict]:
    if type(window) is not int or window <= 0 or type(frequency) is not int or frequency <= 0:
        raise ValueError('window and frequency must be positive integers')
    _budget(budget)
    simulation = Simulation(instance)
    plans, actions, deviations, predictions = [], {}, [], {}
    signature = None
    started = perf_counter()
    fallback_dispatches = 0
    while not simulation.finished:
        view = temporal_observation(simulation)
        current = (tuple(t.id for t in view.tasks), tuple((r.id, r.unavailable) for r in view.robots))
        if view.tasks and (simulation.tick % frequency == 0 or current != signature):
            plan = plan_schedule(view, min(instance.horizon, simulation.tick + window), budget=budget)
            plans.append(plan)
            actions = {}
            for action in plan['assignments']:
                actions.setdefault(action['tick'], []).append(action)
            signature = current
        for action in actions.get(simulation.tick, []):
            robot, task = simulation.robots[action['robot_id']], simulation.tasks[action['task_id']]
            if robot.available and task.state == TaskState.PENDING:
                simulation.assign(robot.id, task.id)
                predictions[task.id] = deepcopy(plans[-1]['tasks'][task.id])
        # ponytail: infeasible short windows retain backlog and use V1 FIFO now;
        # optional-task horizon optimization belongs in a larger-scale scheduler.
        if plans and plans[-1]['objective'] is None:
            for robot_id, task_id in fifo(simulation.observation())['assignments']:
                simulation.assign(robot_id, task_id)
                fallback_dispatches += 1
        before = len(simulation.events)
        simulation.step()
        for event in simulation.events[before:]:
            if event['kind'] in {'collected', 'delivered'}:
                field = 'collected_tick' if event['kind'] == 'collected' else 'completed_tick'
                expected = predictions.get(event['task_id'], {}).get(field)
                if expected is not None:
                    deviations.append(dict(task_id=event['task_id'], event=event['kind'],
                                           delta=event['tick'] - expected))
    return simulation, dict(replans=len(plans), plans=plans, window=window, frequency=frequency,
        fallback_dispatches=fallback_dispatches, dispatch_plan_deviations=deviations,
        solver_seconds=sum(p['solver_seconds'] for p in plans), total_seconds=perf_counter() - started,
        information='revealed unfinished tasks, current robots/resources; no future calendar; optimistic future availability')


def run_priority(instance: Instance, policy: dict[str, list[str]]) -> Simulation:
    """Fixed robot queues. Dispatch head only when revealed and robot available."""
    if set(policy) != set(instance.robots):
        raise ValueError('policy must specify every robot')
    flattened = [t for queue in policy.values() for t in queue]
    if len(flattened) != len(set(flattened)) or set(flattened) != set(instance.tasks):
        raise ValueError('policy must contain every task exactly once')
    for robot_id, queue in policy.items():
        for task_id in queue:
            task = instance.tasks[task_id]
            if task.load > instance.robots[robot_id].capacity or shortest_path(
                    instance.grid, instance.robots[robot_id].position, task.pickup) is None:
                raise ValueError('policy contains an incompatible assignment')
    simulation = Simulation(instance)
    queues = deepcopy(policy)
    while not simulation.finished:
        for robot_id in sorted(queues):
            queue, robot = queues[robot_id], simulation.robots[robot_id]
            if queue and robot.available and simulation.tasks[queue[0]].state == TaskState.PENDING:
                simulation.assign(robot_id, queue.pop(0))
        simulation.step()
    return simulation


def optimize_priority(instance: Instance, scenarios: list[list[dict]], *, max_policies: int = 10000) -> dict:
    """Finite-scenario minimax over fixed robot assignment and task-priority queues.

    The policy sees current availability and task revelation only during replay.
    All decisions (queues) are here-and-now. Every declared scenario must finish.
    Lexicographic objective: max total tardiness, then max makespan. Exhaustive
    enumeration proves optimality only for this finite class and scenario set.
    """
    if not scenarios:
        raise ValueError('at least one scenario is required')
    if type(max_policies) is not int or max_policies <= 0:
        raise ValueError('max_policies must be a positive integer')
    started = perf_counter()
    configurations = []
    for scenario in scenarios:
        data = instance.to_dict()
        data['unavailability'] = deepcopy(scenario)
        configurations.append(from_dict(data))
    tasks = sorted(instance.tasks)
    robots = sorted(instance.robots)
    domains = [[r for r in robots if instance.robots[r].capacity >= instance.tasks[t].load
                and shortest_path(instance.grid, instance.robots[r].position, instance.tasks[t].pickup) is not None]
               for t in tasks]
    seen, evaluated, failures, best, best_values, objective = set(), 0, 0, None, None, None
    exhausted = True
    # ponytail: factorial exhaustive policy search is intentional for certifiable
    # microcases; max_policies bounds it and prevents unsupported optimum claims.
    for order in permutations(tasks):
        for assignment in product(*domains):
            owner = dict(zip(tasks, assignment))
            key = tuple(tuple(t for t in order if owner[t] == r) for r in robots)
            if key in seen:
                continue
            if evaluated >= max_policies:
                exhausted = False
                break
            seen.add(key)
            evaluated += 1
            policy = {r: list(queue) for r, queue in zip(robots, key)}
            values = [metrics(run_priority(config, policy)) for config in configurations]
            if any(v['completion_rate'] != 1.0 for v in values):
                failures += 1
                continue
            candidate = (max(v['total_tardiness'] for v in values), max(v['makespan'] for v in values))
            if objective is None or candidate < objective:
                best, best_values, objective = policy, values, candidate
        if not exhausted:
            break
    return dict(status=('OPTIMAL' if best is not None else 'INFEASIBLE') if exhausted else
                ('FEASIBLE' if best is not None else 'UNKNOWN'), optimal=exhausted and best is not None,
                policy=best, objective=list(objective) if objective is not None else None,
                scenario_metrics=best_values, scenarios=deepcopy(scenarios), policies_evaluated=evaluated,
                infeasible_policies=failures, enumeration_complete=exhausted,
                total_seconds=perf_counter() - started,
                guarantee='only declared finite calendars and fixed robot queues; completion required in every scenario')


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('instance', type=Path)
    parser.add_argument('--method', choices=['nominal', 'rolling', 'priority', 'robust'], default='nominal')
    parser.add_argument('--budget', type=float, default=1.0)
    parser.add_argument('--window', type=int, default=20)
    parser.add_argument('--frequency', type=int, default=3)
    parser.add_argument('--scenarios', type=Path, help='JSON array of outage-calendar arrays; robust only')
    parser.add_argument('--max-policies', type=int, default=10000)
    parser.add_argument('--json', type=Path)
    args = parser.parse_args(argv)
    try:
        instance = load_instance(args.instance)
        if args.method == 'nominal':
            planning = solve_schedule(instance, budget=args.budget)
            simulation, validation = execute_schedule(instance, planning)
            output = dict(method=args.method, plan=planning, validation=validation,
                          metrics=metrics(simulation), trace=simulation.trace())
        elif args.method == 'rolling':
            simulation, planning = run_rolling(instance, window=args.window, frequency=args.frequency, budget=args.budget)
            output = dict(method=args.method, planning=planning, metrics=metrics(simulation), trace=simulation.trace())
        else:
            scenarios = ([[]] if args.method == 'priority' else
                         json.loads(args.scenarios.read_text(encoding='utf-8')) if args.scenarios else
                         [[], instance.unavailability])
            planning = optimize_priority(instance, scenarios, max_policies=args.max_policies)
            output = dict(method=args.method, optimization=planning)
            if planning['policy'] is not None:
                simulation = run_priority(instance, planning['policy'])
                output.update(metrics=metrics(simulation), trace=simulation.trace())
        if args.json:
            args.json.parent.mkdir(parents=True, exist_ok=True)
            args.json.write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        print(json.dumps({k: v for k, v in output.items() if k != 'trace'}, ensure_ascii=False, indent=2))
        return 0
    except (ValueError, OSError) as error:
        parser.error(str(error))


if __name__ == '__main__':
    raise SystemExit(main())
